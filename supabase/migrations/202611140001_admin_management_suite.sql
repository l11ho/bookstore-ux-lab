create or replace function public.admin_delete_book(p_book_id integer)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_book public.bookstore_books;
begin
  if not public.is_bookstore_admin() then
    raise exception 'ADMIN_REQUIRED';
  end if;

  update public.bookstore_books
  set is_active = false, updated_at = now()
  where id = p_book_id
  returning * into v_book;

  if not found then
    raise exception 'BOOK_NOT_FOUND';
  end if;

  return pg_catalog.jsonb_build_object('id', v_book.id, 'is_active', v_book.is_active);
end;
$$;

revoke all on function public.admin_delete_book(integer) from public, anon;
grant execute on function public.admin_delete_book(integer) to authenticated;

