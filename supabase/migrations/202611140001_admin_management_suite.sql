create or replace function public.admin_get_overview()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_result jsonb;
begin
  if not public.is_bookstore_admin() then
    raise exception 'ADMIN_REQUIRED';
  end if;

  select pg_catalog.jsonb_build_object(
    'totalOrders', (select count(*)::integer from public.bookstore_orders),
    'processingOrders', (select count(*)::integer from public.bookstore_orders where order_status = 'processing'),
    'demoRevenueCents', (select coalesce(sum(total_cents), 0)::integer from public.bookstore_orders where payment_status = 'succeeded_demo' and order_status <> 'cancelled'),
    'customerCount', (select count(distinct user_id)::integer from public.bookstore_orders),
    'totalBooks', (select count(*)::integer from public.bookstore_books where is_active),
    'lowStockCount', (select count(*)::integer from public.bookstore_books where is_active and stock <= 3),
    'orders', coalesce((
      select pg_catalog.jsonb_agg(pg_catalog.to_jsonb(order_row) order by order_row.created_at desc)
      from (
        select id, order_number, user_id, created_at, subtotal_cents, shipping_cents,
          total_cents, payment_method, payment_status, order_status, shipping_address, items
        from public.bookstore_orders
        order by created_at desc
        limit 200
      ) as order_row
    ), '[]'::jsonb),
    'books', coalesce((
      select pg_catalog.jsonb_agg(pg_catalog.to_jsonb(book_row) order by book_row.display_order, book_row.id)
      from public.bookstore_books as book_row
    ), '[]'::jsonb),
    'customers', coalesce((
      select pg_catalog.jsonb_agg(customer_data.payload order by customer_data.last_order_at desc)
      from (
        select
          grouped.user_id,
          grouped.last_order_at,
          pg_catalog.jsonb_build_object(
            'userId', grouped.user_id,
            'name', coalesce(grouped.full_name, 'Покупатель'),
            'email', coalesce(grouped.email, ''),
            'phone', coalesce(grouped.phone, ''),
            'ordersCount', grouped.orders_count,
            'totalSpentCents', grouped.total_spent_cents,
            'lastOrderAt', grouped.last_order_at,
            'orders', grouped.order_history
          ) as payload
        from (
          select
            o.user_id,
            max(o.shipping_address ->> 'full_name') as full_name,
            max(o.shipping_address ->> 'email') as email,
            max(o.shipping_address ->> 'phone') as phone,
            count(*)::integer as orders_count,
            coalesce(sum(o.total_cents) filter (where o.payment_status = 'succeeded_demo' and o.order_status <> 'cancelled'), 0)::integer as total_spent_cents,
            max(o.created_at) as last_order_at,
            (
              select coalesce(pg_catalog.jsonb_agg(
                pg_catalog.jsonb_build_object(
                  'id', customer_order.id,
                  'orderNumber', customer_order.order_number,
                  'createdAt', customer_order.created_at,
                  'totalCents', customer_order.total_cents,
                  'status', customer_order.order_status
                ) order by customer_order.created_at desc
              ), '[]'::jsonb)
              from public.bookstore_orders as customer_order
              where customer_order.user_id = o.user_id
            ) as order_history
          from public.bookstore_orders as o
          group by o.user_id
        ) as grouped
      ) as customer_data
    ), '[]'::jsonb),
    'monthlyRevenue', coalesce((
      select pg_catalog.jsonb_agg(
        pg_catalog.jsonb_build_object(
          'month', pg_catalog.to_char(month_data.month_start, 'YYYY-MM'),
          'label', pg_catalog.to_char(month_data.month_start, 'Mon'),
          'revenueCents', month_data.revenue_cents,
          'ordersCount', month_data.orders_count
        ) order by month_data.month_start
      )
      from (
        select
          months.month_start,
          coalesce(sum(o.total_cents) filter (where o.payment_status = 'succeeded_demo' and o.order_status <> 'cancelled'), 0)::integer as revenue_cents,
          count(o.id)::integer as orders_count
        from pg_catalog.generate_series(
          pg_catalog.date_trunc('month', now()) - interval '5 months',
          pg_catalog.date_trunc('month', now()),
          interval '1 month'
        ) as months(month_start)
        left join public.bookstore_orders as o
          on pg_catalog.date_trunc('month', o.created_at) = months.month_start
        group by months.month_start
      ) as month_data
    ), '[]'::jsonb),
    'topBooks', coalesce((
      select pg_catalog.jsonb_agg(
        pg_catalog.jsonb_build_object(
          'title', top_book.title,
          'quantity', top_book.quantity,
          'revenueCents', top_book.revenue_cents
        ) order by top_book.quantity desc, top_book.revenue_cents desc
      )
      from (
        select
          item ->> 'title' as title,
          sum(coalesce((item ->> 'quantity')::integer, 1))::integer as quantity,
          sum(coalesce(
            (item ->> 'line_total_cents')::integer,
            coalesce((item ->> 'unit_price_cents')::integer, 0) * coalesce((item ->> 'quantity')::integer, 1)
          ))::integer as revenue_cents
        from public.bookstore_orders as o
        cross join lateral pg_catalog.jsonb_array_elements(o.items) as line(item)
        where o.order_status <> 'cancelled'
        group by item ->> 'title'
        order by quantity desc
        limit 8
      ) as top_book
    ), '[]'::jsonb),
    'statusCounts', coalesce((
      select pg_catalog.jsonb_object_agg(status_data.order_status, status_data.order_count)
      from (
        select order_status, count(*)::integer as order_count
        from public.bookstore_orders
        group by order_status
      ) as status_data
    ), '{}'::jsonb)
  )
  into v_result;

  return v_result;
end;
$$;

