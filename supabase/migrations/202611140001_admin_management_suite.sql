create or replace function public.admin_save_book(p_book jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id integer;
  v_sections text[];
  v_book public.bookstore_books;
begin
  if not public.is_bookstore_admin() then
    raise exception 'ADMIN_REQUIRED';
  end if;
  if pg_catalog.jsonb_typeof(p_book) is distinct from 'object' then
    raise exception 'INVALID_BOOK';
  end if;

  v_id := nullif(p_book ->> 'id', '')::integer;
  select coalesce(array_agg(section_value), '{}'::text[])
  into v_sections
  from pg_catalog.jsonb_array_elements_text(coalesce(p_book -> 'sections', '[]'::jsonb)) as sections(section_value);

  if pg_catalog.length(pg_catalog.btrim(coalesce(p_book ->> 'title', ''))) < 2
    or pg_catalog.length(pg_catalog.btrim(coalesce(p_book ->> 'author', ''))) < 2
    or pg_catalog.length(pg_catalog.btrim(coalesce(p_book ->> 'category', ''))) < 2 then
    raise exception 'INVALID_BOOK_DETAILS';
  end if;

  if coalesce((p_book ->> 'priceCents')::integer, 0) < 1
    or coalesce((p_book ->> 'priceCents')::integer, 0) > 100000000
    or coalesce((p_book ->> 'stock')::integer, 0) < 0
    or coalesce((p_book ->> 'stock')::integer, 0) > 1000000 then
    raise exception 'INVALID_BOOK_PRICE_OR_STOCK';
  end if;

  if coalesce(p_book ->> 'coverUrl', '') <> ''
    and (p_book ->> 'coverUrl') !~ '^https?://' then
    raise exception 'INVALID_COVER_URL';
  end if;

  if v_id is null then
    insert into public.bookstore_books (
      title, author, price_cents, category, description, cover_note, cover_style, cover_url,
      sections, publisher, publication_year, pages, shelf, stock, age, dimensions, weight,
      binding, delivery, is_preorder, release_date, is_active, display_order, updated_at
    ) values (
      pg_catalog.btrim(p_book ->> 'title'),
      pg_catalog.btrim(p_book ->> 'author'),
      (p_book ->> 'priceCents')::integer,
      pg_catalog.btrim(p_book ->> 'category'),
      coalesce(p_book ->> 'description', ''),
      coalesce(p_book ->> 'coverNote', ''),
      coalesce(nullif(p_book ->> 'coverStyle', ''), 'default'),
      nullif(pg_catalog.btrim(coalesce(p_book ->> 'coverUrl', '')), ''),
      v_sections,
      coalesce(nullif(p_book ->> 'publisher', ''), 'BookStore Editions'),
      coalesce(nullif(p_book ->> 'year', '')::integer, 2026),
      coalesce(nullif(p_book ->> 'pages', '')::integer, 320),
      coalesce(nullif(p_book ->> 'shelf', ''), 'A-01'),
      coalesce((p_book ->> 'stock')::integer, 0),
      coalesce(nullif(p_book ->> 'age', ''), '16+'),
      coalesce(nullif(p_book ->> 'dimensions', ''), '145×215×20 мм'),
      coalesce(nullif(p_book ->> 'weight', ''), '420 г'),
      coalesce(nullif(p_book ->> 'binding', ''), 'Твёрдый переплёт'),
      coalesce(nullif(p_book ->> 'delivery', ''), 'Доставка по России — 2–5 дней'),
      coalesce((p_book ->> 'isPreorder')::boolean, false),
      coalesce(p_book ->> 'releaseDate', ''),
      coalesce((p_book ->> 'isActive')::boolean, true),
      coalesce(nullif(p_book ->> 'displayOrder', '')::integer, 1000),
      now()
    ) returning * into v_book;
  else
    update public.bookstore_books set
      title = pg_catalog.btrim(p_book ->> 'title'),
      author = pg_catalog.btrim(p_book ->> 'author'),
      price_cents = (p_book ->> 'priceCents')::integer,
      category = pg_catalog.btrim(p_book ->> 'category'),
      description = coalesce(p_book ->> 'description', ''),
      cover_note = coalesce(p_book ->> 'coverNote', ''),
      cover_style = coalesce(nullif(p_book ->> 'coverStyle', ''), 'default'),
      cover_url = nullif(pg_catalog.btrim(coalesce(p_book ->> 'coverUrl', '')), ''),
      sections = v_sections,
      publisher = coalesce(nullif(p_book ->> 'publisher', ''), 'BookStore Editions'),
      publication_year = coalesce(nullif(p_book ->> 'year', '')::integer, 2026),
      pages = coalesce(nullif(p_book ->> 'pages', '')::integer, 320),
      shelf = coalesce(nullif(p_book ->> 'shelf', ''), 'A-01'),
      stock = coalesce((p_book ->> 'stock')::integer, 0),
      age = coalesce(nullif(p_book ->> 'age', ''), '16+'),
      dimensions = coalesce(nullif(p_book ->> 'dimensions', ''), '145×215×20 мм'),
      weight = coalesce(nullif(p_book ->> 'weight', ''), '420 г'),
      binding = coalesce(nullif(p_book ->> 'binding', ''), 'Твёрдый переплёт'),
      delivery = coalesce(nullif(p_book ->> 'delivery', ''), 'Доставка по России — 2–5 дней'),
      is_preorder = coalesce((p_book ->> 'isPreorder')::boolean, false),
      release_date = coalesce(p_book ->> 'releaseDate', ''),
      is_active = coalesce((p_book ->> 'isActive')::boolean, true),
      display_order = coalesce(nullif(p_book ->> 'displayOrder', '')::integer, 1000),
      updated_at = now()
    where id = v_id
    returning * into v_book;

    if not found then
      raise exception 'BOOK_NOT_FOUND';
    end if;
  end if;

  return pg_catalog.to_jsonb(v_book);
end;
$$;

