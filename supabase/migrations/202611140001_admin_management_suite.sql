-- BookStore admin management suite.
-- Adds a database-backed catalog, customer summaries, analytics and protected catalog RPCs.
-- Run this file in Supabase SQL Editor after the existing Admin migration.

create table if not exists public.bookstore_books (
  id integer generated by default as identity primary key,
  title text not null,
  author text not null,
  price_cents integer not null check (price_cents > 0),
  category text not null default 'Другое',
  description text not null default '',
  cover_note text not null default '',
  cover_style text not null default 'default',
  cover_url text,
  sections text[] not null default '{}',
  publisher text not null default 'BookStore Editions',
  publication_year integer not null default 2026,
  pages integer not null default 320,
  shelf text not null default 'A-01',
  stock integer not null default 0 check (stock >= 0),
  age text not null default '16+',
  dimensions text not null default '145×215×20 мм',
  weight text not null default '420 г',
  binding text not null default 'Твёрдый переплёт',
  delivery text not null default 'Доставка по России — 2–5 дней',
  is_preorder boolean not null default false,
  release_date text not null default '',
  is_active boolean not null default true,
  display_order integer not null default 1000,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists bookstore_books_active_order_idx
  on public.bookstore_books (is_active, display_order, id);

alter table public.bookstore_books enable row level security;
revoke all on table public.bookstore_books from anon, authenticated;
grant select on table public.bookstore_books to anon, authenticated;

drop policy if exists "Public can read active bookstore books" on public.bookstore_books;
create policy "Public can read active bookstore books"
  on public.bookstore_books for select to anon, authenticated
  using (is_active = true);

